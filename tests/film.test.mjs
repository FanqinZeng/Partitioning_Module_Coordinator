import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,statSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {run,G01,BAD,GOOD,metrics,exact} from '../site/engines/course.js';
const load=path=>JSON.parse(readFileSync(new URL('../'+path,import.meta.url),'utf8'));
const sha=path=>createHash('sha256').update(readFileSync(new URL('../'+path,import.meta.url))).digest('hex');
const story=load('video/home/storyboard.json'),data=load('video/home/data.json'),film=load('site/media/home/film.json');

test('home film examples are generated by the current course engines',()=>{
 assert.deepEqual(data.graph,G01);assert.equal(data.badMetrics.cut,metrics(G01,BAD).cut);assert.equal(data.goodMetrics.cut,metrics(G01,GOOD).cut);
 for(const method of ['initial','kl','fm','spectral','recursive']){
  const current=run(method,G01,method==='recursive'?{k:3}:{});
  assert.deepEqual(data[method].result.assignment,current.result.assignment);assert.equal(data[method].result.metrics.cut,current.result.metrics.cut);
 }
 assert.equal(data.roundRobin.result.metrics.cut,run('multiway',G01,{k:3,capacity:2,strategy:'round-robin'}).result.metrics.cut);
 assert.equal(data.refined.result.metrics.cut,run('multiway',G01,{k:3,capacity:2}).result.metrics.cut);
 assert.equal(data.oracle.best.cut,exact(G01,{k:3,capacity:2}).best.cut);
 assert.equal(data.counts.unlabeled100,String(2n**99n-1n));assert.equal(data.counts.unlabeled100.length,30);
 for(const [path,digest]of Object.entries(film.sourceFiles))assert.equal(sha(path),digest,path+' changed after rendering');
});
test('bilingual timeline has complete chapters, aligned captions and zero reading violations',()=>{
 assert.equal(story.scenes.length,16);assert.equal(story.scenes.reduce((s,x)=>s+x.duration,0),190);assert.equal(film.duration,190);
 assert.equal(film.captions.length,30);assert.equal(film.captions[0].start,0);assert.equal(film.captions.at(-1).end,190);
 let cursor=0;
 for(const c of film.captions){assert.equal(c.start,cursor);const minimum=Math.max([...c.zh].filter(c=>!c.match(/\s/)).length/4.5,c.en.trim().length/15)+.8;assert.ok(c.end-c.start>=minimum,c.zh);cursor=c.end;}
 assert.deepEqual(film.readingViolations,{zh:0,en:0});assert.equal(film.chapters[0].time,0);assert.equal(film.chapters.at(-1).time,180);
 for(const language of ['zh','en']){const vtt=readFileSync(new URL(`../site/media/home/intro.${language}.vtt`,import.meta.url),'utf8');assert.equal((vtt.match(/ --> /g)||[]).length,30);}
});
test('delivered MP4s match the decoded and checked video artifacts',()=>{
 const validation=load('video/home/validation.json');
 for(const language of ['zh','en']){
  const path=`site/media/home/intro.${language}.mp4`,report=validation.versions[language];
  assert.equal(sha(path),film.versions[language].sha256);assert.equal(sha(path),report.sha256);assert.ok(report.fullDecode&&report.faststart);assert.equal(report.frames,5700);assert.equal(report.fps,30);assert.equal(report.width,1920);assert.equal(report.height,1080);assert.equal(report.audioCodec,'aac');assert.equal(report.readingViolations,0);
  assert.ok(statSync(new URL('../'+path,import.meta.url)).size>1000000);
 }
});
